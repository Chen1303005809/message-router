def customer_name_for_group(group_name: str | None) -> str:
    """Return the configured customer name for an exact group name match."""
    if not isinstance(group_name, str) or not group_name.strip():
        return ""
    value = CUSTOMER_NAME_BY_GROUP.get(group_name.strip())
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, list):
        return "、".join(name.strip() for name in value if name.strip())
    return ""
